#[cfg(test)]
mod tests {
    use super::*;

    /// Primo testo (quello inglese) di ogni chiamata t("..", ..), l("..", ..), f("..", ..) in gui.rs.
    fn keys_in_gui() -> Vec<String> {
        let src = concat!(include_str!("gui.rs"), include_str!("gui/welcome.rs"));
        let b = src.as_bytes();
        let mut keys = Vec::new();
        for pat in ["t(", "l(", "f("] {
            let mut from = 0;
            while let Some(pos) = src[from..].find(pat) {
                let start = from + pos;
                from = start + pat.len();
                if start > 0 && (b[start - 1].is_ascii_alphanumeric() || b[start - 1] == b'_') {
                    continue;
                }
                let mut i = from;
                while i < b.len() && b[i].is_ascii_whitespace() {
                    i += 1;
                }
                if i >= b.len() || b[i] != b'"' {
                    continue;
                }
                let mut j = i + 1;
                while b[j] != b'"' {
                    j += if b[j] == b'\\' { 2 } else { 1 };
                }
                let mut k = j + 1;
                while b[k] == b',' || b[k].is_ascii_whitespace() {
                    k += 1;
                }
                if b[k] == b'"' {
                    // la chiave nelle tabelle e scritta con gli stessi escape del sorgente
                    keys.push(src[i + 1..j].replace("\\\"", "\"").replace("\\n", "\n"));
                }
            }
        }
        keys
    }

    #[test]
    fn ogni_testo_e_tradotto() {
        let keys = keys_in_gui();
        assert!(keys.len() > 100, "trovati solo {} testi", keys.len());
        for lang in [Lang::Zh, Lang::De, Lang::Es, Lang::Fr] {
            for k in &keys {
                assert!(get(lang, k).is_some(), "manca la traduzione {:?} per {k:?}", lang.name());
            }
        }
    }

    #[test]
    fn segnaposto_uguali() {
        for table in [ZH, DE, ES, FR] {
            for (en, tr) in table {
                for n in 0..4 {
                    let p = format!("{{{n}}}");
                    assert_eq!(en.contains(&p), tr.contains(&p), "{en:?} / {tr:?}");
                }
            }
        }
    }
}
